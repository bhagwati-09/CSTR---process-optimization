print(f" Stream B fraction  : {xB/(xA+xB):.1%}  (requirement: >=40%)")
print("=" * 44)
print(f"\n Solver status: {result.solver.termination_condition}")

# Tighten quality: now Stream B must be >= 60% of product

model2 = ConcreteModel()
