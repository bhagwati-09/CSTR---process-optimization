# Sensitivity Analysis

import numpy as np
import matplotlib.pyplot as plt
from scipy.optimize import minimize as sci_min

# Fixed parameters
k0=1e8; Ea=65000; R=8.314; C_A0=2.0; F_A0=5.0

def solve_cstr(V, X_MIN=0.80):

    def objective(vars):
        T, X = vars
        return 0.5*(T - 298) + 100.0*(1 - X)

    def cstr_balance(vars):
        # Must equal zero: CSTR material balance
        T, X = vars
        k = k0 * np.exp(-Ea / (R * T))
        return F_A0*X - k*C_A0*(1 - X)*V

    def min_conv(vars):
        # Must be >= 0: conversion spec
        return vars[1] - X_MIN

    result = sci_min(
        fun         = objective,
        x0          = [350.0, 0.85],          # initial guess
        method      = 'SLSQP',
        bounds      = [(300, 450), (0.01, 0.999)],
        constraints = [
            {'type': 'eq',   'fun': cstr_balance},
            {'type': 'ineq', 'fun': min_conv}
        ],
        options = {'ftol': 1e-9, 'maxiter': 500}
    )
    return result.x[0], result.x[1], result.fun

# Part 1: vary reactor volume
V_range    = np.linspace(100, 1000, 30)
T_v, X_v, cost_v = [], [], []

for V in V_range:
    T_opt, X_opt, c_opt = solve_cstr(V, X_MIN=0.80)
    T_v.append(T_opt)
    X_v.append(X_opt * 100)
    cost_v.append(c_opt)

T_v = np.array(T_v); X_v = np.array(X_v); cost_v = np.array(cost_v)
print(f"Arrays built — V:{V_range.shape}, T:{T_v.shape}, cost:{cost_v.shape}")

# Part 2: vary conversion spec
Xmin_range  = np.linspace(0.60, 0.95, 30)
T_x, cost_x = [], []

for xmin in Xmin_range:
    T_opt, X_opt, c_opt = solve_cstr(V=500.0, X_MIN=xmin)
    T_x.append(T_opt)
    cost_x.append(c_opt)

T_x = np.array(T_x); cost_x = np.array(cost_x)
