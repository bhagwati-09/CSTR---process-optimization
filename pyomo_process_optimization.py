# Phase 1: Blending Optimization

from pyomo.environ import(
    ConcreteModel, Var, NonNegativeReals,
    Objective, Constraint, minimize, SolverFactory
)
import os

# Solver path
ipopt_path = os.path.expanduser('~/.idaes/bin/ipopt')
solver = SolverFactory('ipopt', executable=ipopt_path)

model = ConcreteModel()

# Decision variables: how much of each stream to purchase
model.x_A = Var(domain=NonNegativeReals)  # kg of Stream A @ €3/kg
model.x_B = Var(domain=NonNegativeReals)  # kg of Stream B @ €5/kg

# Objective: minimize total purchase cost
model.cost = Objective(
    expr  = 3 * model.x_A + 5 * model.x_B,
    sense = minimize
)

# Constraint 1: need at least 100 kg of product
model.min_product = Constraint(expr = model.x_A + model.x_B >= 100)

# Constraint 2: Stream A supplier can only send 80 kg max
model.max_A = Constraint(expr = model.x_A <= 80)

# Constraint 3: Stream B supplier can only send 60 kg max
model.max_B = Constraint(expr = model.x_B <= 60)

# Constraint 4: product quality - at least 40% must be Stream B
# Rearranged from: x_B / (x_A + x_B) >= 0.40
# To avoid division: 0.6 * x_B >= 0.4 * x_A
model.quality = Constraint(expr = 0.6 * model.x_B >= 0.4 * model.x_A)

result = solver.solve(model, tee=False)

xA = model.x_A()
xB = model.x_B()

print("=" * 44)
print(" BLENDING OPTIMIZATION - RESULTS")
print("=" * 44)
print(f" Stream A purchased : {xA:.2f} kg @ €3/kg")
print(f" Stream B purchased : {xB:.2f} kg @ €5/kg")
