# Phase 2: CSTR Operating Cost Minimization

import idaes

from pyomo.environ import(
    ConcreteModel, Var, Objective, Constraint,
    minimize, SolverFactory, exp, value
)
import os

ipopt_path = os.path.expanduser('~/.ideas/bin/ipopt')
solver = SolverFactory('ipopt')

# Process parameters
k0  = 1e8          # pre-exponential factor   [1/s]
Ea  = 65000        # activation energy        [J/mol]
R   = 8.314        # gas constant             [J/mol.K]
C_A0  = 2.0        # feed concentration       [mol/L]
F_A0  = 5.0        # molar feed rate          [mol/s]
V     = 500.0      # reactor volume           [L]  - fixed, given

model = ConcreteModel()

# Decision variables
model.T = Var(bounds=(300, 450),  initialize=350)       # Temperature [K]
model.X = Var(bounds=(0.01, 0.999),  initialize=0.8)    # Conversion  [-]

# Objective function
# Heating cost: proportional to temperature rise above 298 K (ambient)
# Revenue loss: cost of feed leaving reactor unreacted
model.obj = Objective(
    expr  = 0.5 * (model.T - 298) + 100.0 * (1 - model.X),
    sense = minimize
)

# Constraints
# 1. CSTR material balance (equality)
# Rate of A converted = rate of reaction in reactor
# F_A0 * X = k(T) * C_A0 * (1-X) * V
model.cstr_balance = Constraint(
    expr = F_A0 * model.X ==
    k0 * exp(-Ea / (R * model.T)) * C_A0 * (1 - model.X) * V
)

# 2. Minimum conversion spec (product quality requirement)
model.min_conversion = Constraint(expr = model.X >= 0.80)
result = solver.solve(model, tee=False)

T_opt    = value(model.T)
X_opt    = value(model.X)
heat_cost = 0.5 * (T_opt - 298)
rev_loss  = 100.0 * (1 - X_opt)
total     = heat_cost + rev_loss

print("=" * 52)
print("  CSTR OPTIMIZATION - OPTIMAL SOLUTION")
print("=" * 52)
print(f"  Optimal temperature  : {T_opt:.1f} K ({T_opt-273.15:.1f} degC)")
print(f"  Optimal conversion   : {X_opt:.4f}  ({X_opt*100:.2f}%)")
print(f"  ___________________________________________")
print(f"  Heating cost          : €{heat_cost:.2f}/hr")
print(f"  Revenue loss (waste)  : €{rev_loss:.2f}/hr")
print(f"  Total minimum cost    : €{total:.2f}/hr")
print("=" * 52)
print(f"   Solver status : {result.solver.termination_condition}")

